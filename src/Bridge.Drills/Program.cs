using System.Globalization;
using System.Text;
using System.Text.Json;
using Bridge.Drills;
using Bridge.PlatformSim;

// dotnet run --project src/Bridge.Drills -- [--quick] [--kafka host:port] [--only name] [--out reports]
string? kafka = null, only = null, outDir = "reports";
var quick = false;
for (var i = 0; i < args.Length; i++)
{
    switch (args[i])
    {
        case "--kafka": kafka = args[++i]; break;
        case "--only": only = args[++i]; break;
        case "--out": outDir = args[++i]; break;
        case "--quick": quick = true; break;
        default: Console.Error.WriteLine($"unknown argument {args[i]}"); return 2;
    }
}

var scale = quick ? 0.5 : 1.0;
int M(int n) => Math.Max(6, (int)(n * scale));
var drills = new List<DrillConfig>
{
    new()
    {
        Name = "steady",
        Description = "No faults: the baseline every other drill is compared with.",
        Merchants = M(40),
    },
    new()
    {
        Name = "platform-chaos",
        Description = "The platform duplicates 15 % of events, reorders 15 %, loses 3 % of state events, sends 30 % of volume reports in the old schema and a broken message now and then.",
        Merchants = M(60),
        Seed = 11,
        Chaos = new ChaosOptions { Duplicate = 0.15, Reorder = 0.15, Drop = 0.03, OldVolumeSchema = 0.3, PoisonPerHundredTicks = 4 },
        Consumers = 3,
    },
    new()
    {
        Name = "crashes-and-contention",
        Description = "Consumers crash between the CRM write and the offset commit (5 %), three consumers rebalance, people edit the same rows, Dataverse answers slowly (up to 25 ms) and fails $batch requests with 503 now and then.",
        Merchants = M(50),
        Seed = 23,
        Chaos = new ChaosOptions { Duplicate = 0.05, Reorder = 0.05, Drop = 0, OldVolumeSchema = 0.2, PoisonPerHundredTicks = 1 },
        Consumers = 3,
        CrashAfterApply = 0.05,
        MaxLatencyMs = 25,
        FailBatchesEveryTicks = 15,
        EditsPerTick = 3,
    },
    new()
    {
        Name = "throttling",
        Description = "Dataverse service protection set tight (150 requests per 3 s for the bridge's user): 429 with Retry-After all through the run.",
        Merchants = M(30),
        Seed = 31,
        Chaos = new ChaosOptions { Duplicate = 0.05, Reorder = 0.05, Drop = 0.01, OldVolumeSchema = 0.2, PoisonPerHundredTicks = 1 },
        ThrottleLimit = 150,
        ThrottleWindowSeconds = 3,
    },
};
if (only is not null) drills = drills.Where(d => d.Name == only).ToList();
if (kafka is not null && only is null) drills = drills.Take(2).ToList(); // against a real broker: baseline and chaos

var results = new List<DrillResult>();
foreach (var config in drills)
{
    Console.WriteLine($"drill {config.Name} ({config.Merchants} merchants{(kafka is null ? "" : ", Kafka " + kafka)})...");
    DrillResult result;
    try
    {
        result = await new Drill(config, kafka).RunAsync(CancellationToken.None);
    }
    catch (OperationCanceledException)
    {
        result = new DrillResult(config.Name, config.Description, false, [new Check("Finished in time", false, $"did not settle within {config.Timeout}")], new Dictionary<string, double>(), config.Timeout.TotalSeconds);
    }
    results.Add(result);
    foreach (var c in result.Checks) Console.WriteLine($"  {(c.Passed ? "pass" : "FAIL")}  {c.Name}: {c.Detail}");
    Console.WriteLine($"  {string.Join(", ", result.Numbers.Select(kv => $"{kv.Key}={kv.Value}"))} in {result.Seconds}s");
}

Directory.CreateDirectory(outDir);
var file = kafka is null ? "drills" : "drills-kafka";
var report = new
{
    generatedAt = DateTimeOffset.UtcNow,
    transport = kafka is null ? "in-memory log (Kafka delivery semantics)" : "Apache Kafka",
    passed = results.All(r => r.Passed),
    drills = results,
};
await File.WriteAllTextAsync(Path.Combine(outDir, file + ".json"), JsonSerializer.Serialize(report, new JsonSerializerOptions { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase }));

var md = new StringBuilder();
md.AppendLine(CultureInfo.InvariantCulture, $"# Sync drills ({report.transport})");
md.AppendLine();
md.AppendLine("Generated by `dotnet run --project src/Bridge.Drills`; do not edit by hand.");
md.AppendLine();
foreach (var r in results)
{
    md.AppendLine(CultureInfo.InvariantCulture, $"## {r.Name}: {(r.Passed ? "passed" : "FAILED")} in {r.Seconds} s");
    md.AppendLine();
    md.AppendLine(r.Description);
    md.AppendLine();
    md.AppendLine("| Check | Result |");
    md.AppendLine("| --- | --- |");
    foreach (var c in r.Checks) md.AppendLine(CultureInfo.InvariantCulture, $"| {c.Name} | {(c.Passed ? "pass" : "**fail**")}: {c.Detail} |");
    md.AppendLine();
    md.AppendLine(string.Join(", ", r.Numbers.Select(kv => $"{kv.Key.Replace('_', ' ')} {kv.Value.ToString(CultureInfo.InvariantCulture)}")) + ".");
    md.AppendLine();
}
await File.WriteAllTextAsync(Path.Combine(outDir, file.ToUpperInvariant().Replace('-', '_') + ".md"), md.ToString());
Console.WriteLine(report.passed ? "all drills passed" : "DRILLS FAILED");
return report.passed ? 0 : 1;
