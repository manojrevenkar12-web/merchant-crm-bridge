using System.Text.Json;
using System.Text.Json.Nodes;

namespace Bridge.Alm;

/// <summary>The plan as a committed file (alm/metadata-plan.json): a schema change shows up in review as a
/// change to the requests it will make. Assembly content is a placeholder; it comes from the build.</summary>
public static class PlanDocument
{
    public static string Render(DataverseModel m, IReadOnlyList<Step> plan)
    {
        var doc = new JsonObject
        {
            ["$comment"] = "Generated by `dotnet run --project src/Bridge.Alm -- plan --out alm/metadata-plan.json` from dataverse/model.json; do not edit by hand.",
            ["solution"] = m.SolutionUniqueName,
            ["version"] = m.SolutionVersion,
            ["steps"] = new JsonArray(plan.Select(s =>
            {
                var o = new JsonObject { ["id"] = s.Id, ["kind"] = s.Kind.ToString(), ["description"] = s.Description.Trim() };
                if (s.FindPath is not null) o["find"] = s.FindPath;
                if (s.Path is not null) o["post"] = s.Path;
                if (s.UpdatePath is not null) o["patch"] = s.UpdatePath;
                if (s.Body is not null) o["body"] = Trim(s.Body.DeepClone());
                return (JsonNode)o;
            }).ToArray()),
        };
        return doc.ToJsonString(DataverseModel.Json) + "\n";
    }

    // The flow definition is long and has its own file; the plan shows where it comes from.
    private static JsonNode Trim(JsonNode body)
    {
        if (body is JsonObject o && o["clientdata"] is not null) o["clientdata"] = "(dataverse/flows: the flow definition)";
        return body;
    }
}
